export function t(key, lang = 'id') {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.id;
  return dict[key] || TRANSLATIONS.id[key] || key;
}

export function translateCategory(cat, lang = 'id') {
  if (lang === 'id') return cat;
  const map = {
    Religi: 'Religious',
    Alam: 'Nature',
    Bahari: 'Marine',
    Sejarah: 'History',
    Budaya: 'Culture',
    Kuliner: 'Culinary',
  };
  return map[cat] || cat;
}

